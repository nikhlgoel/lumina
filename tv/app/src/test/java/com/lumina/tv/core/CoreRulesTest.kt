class RecommendLogicTest {
    private data class Song(val id: String, val artist: String)

    @Test fun `seeds prefer different artists`() {
        val library = listOf(Song("1", "A"), Song("2", "A"), Song("3", "B"), Song("4", "C"), Song("5", "D"))
        val seeds = RecommendLogic.pickSeeds(library, { it.artist })
        assertEquals(listOf("1", "3", "4"), seeds.map { it.id })
    }

    @Test fun `seeds fall back to repeats when there are too few artists`() {
        val library = listOf(Song("1", "A"), Song("2", "A"), Song("3", "A"))
        assertEquals(listOf("1", "2", "3"), RecommendLogic.pickSeeds(library, { it.artist }).map { it.id })
    }

    @Test fun `seeds with no artist still count`() {
        val library = listOf(Song("1", ""), Song("2", ""))
        assertEquals(2, RecommendLogic.pickSeeds(library, { it.artist }).size)
    }

    @Test fun `no library means no seeds`() {
        assertEquals(emptyList<Song>(), RecommendLogic.pickSeeds(emptyList<Song>(), { it.artist }))
    }

    @Test fun `merge takes turns so one seed does not dominate`() {
        val a = listOf("a1", "a2", "a3")
        val b = listOf("b1", "b2")
        assertEquals(listOf("a1", "b1", "a2", "b2", "a3"), RecommendLogic.merge(listOf(a, b), { it }, emptySet()))
    }

    @Test fun `merge drops what is saved and what repeats`() {
        val out = RecommendLogic.merge(listOf(listOf("x", "y"), listOf("y", "z")), { it }, exclude = setOf("x"))
        assertEquals(listOf("y", "z"), out)
    }

    @Test fun `merge respects the limit and copes with empty input`() {
        assertEquals(2, RecommendLogic.merge(listOf(listOf("1", "2", "3")), { it }, emptySet(), limit = 2).size)
        assertEquals(emptyList<String>(), RecommendLogic.merge(emptyList<List<String>>(), { it }, emptySet()))
    }

    @Test fun `refresh is rate limited and survives a wrong clock`() {
        val now = 5_000_000_000L
        assertTrue(RecommendLogic.isDue(0, now))
        assertEquals(false, RecommendLogic.isDue(now - 1000, now))
        assertTrue(RecommendLogic.isDue(now - RecommendLogic.REFRESH_MS, now))
        assertTrue(RecommendLogic.isDue(now + 1, now))
    }
}

class DensityTest {
    @Test fun `the layout is the same width in dp on every common TV resolution`() {
        // Whatever the pixel width, pixels / density is the design width.
        for (px in listOf(1280, 1920, 2560, 3840)) {
            assertEquals(1733f, px / densityFor(px), 1f)
        }
    }

    @Test fun `a 4K screen is drawn at twice the 1080p density, so it stays sharp`() {
        assertEquals(2f, densityFor(3840) / densityFor(1920), 0.001f)
    }

    @Test fun `a nonsense report cannot break the layout`() {
        assertEquals(0.6f, densityFor(0), 0f)
        assertEquals(0.6f, densityFor(-5), 0f)
        assertEquals(7f, densityFor(100_000), 0f)
    }
}

class LrcTest {
    private val sample = "[ar:Someone]\n[00:08.97] First line\n[00:12.28] Second line\n[01:02.5] Third\n[00:20.00][00:40.00] Chorus\n"

    @Test fun `timed lines are read in order, metadata is skipped, repeated stamps expand`() {
        val lines = Lrc.parse(sample)
        assertEquals(listOf("First line", "Second line", "Chorus", "Chorus", "Third"), lines.map { it.text })
        assertEquals(8_970L, lines.first().timeMs)
        assertEquals(62_500L, lines.last().timeMs)
    }

    @Test fun `the active line is the last one that has started`() {
        val lines = Lrc.parse(sample)
        assertEquals(-1, Lrc.activeIndex(lines, 1_000))
        assertEquals(0, Lrc.activeIndex(lines, 8_970))
        assertEquals(1, Lrc.activeIndex(lines, 15_000))
        assertEquals(4, Lrc.activeIndex(lines, 999_999))
        assertEquals(-1, Lrc.activeIndex(emptyList(), 5))
    }

    @Test fun `youtube titles are cleaned for a lyrics lookup`() {
        assertEquals("Espresso", Lrc.cleanTitle("Espresso (Official Video)"))
        assertEquals("Espresso", Lrc.cleanTitle("Espresso - Official Music Video HD"))
        assertEquals("Panjeban", Lrc.cleanTitle("Panjeban [Lyrics] ft. Someone Else"))
        assertEquals("Gehra Hua", Lrc.cleanTitle("Gehra Hua (From \"Dhurandhar\")"))
        assertEquals("Plain Song", Lrc.cleanTitle("Plain Song"))
    }

    @Test fun `auto-generated channel names become the artist`() {
        assertEquals("Sabrina Carpenter", Lrc.cleanArtist("Sabrina Carpenter - Topic"))
        assertEquals("Shivjot", Lrc.cleanArtist("Shivjot"))
    }

    @Test fun `a timed match of about the right length wins`() {
        val picked = Lrc.pick(listOf(Lrc.Candidate(201.0, "[00:01.0] a", "a"), Lrc.Candidate(176.0, "[00:01.0] b", "b"), Lrc.Candidate(175.0, null, "c")), 175)
        assertEquals("b", picked?.plain)
    }

    @Test fun `a different recording is refused, not shown with the wrong words`() {
        assertNull(Lrc.pick(listOf(Lrc.Candidate(300.0, "[00:01.0] x", "x")), 175))
        assertNull(Lrc.pick(emptyList(), 175))
        assertNull(Lrc.pick(listOf(Lrc.Candidate(175.0, "", "")), 175))
    }

    @Test fun `plain lyrics are used when nothing is timed`() {
        assertEquals("p", Lrc.pick(listOf(Lrc.Candidate(176.0, null, "p")), 175)?.plain)
    }
}


