/**
 * Names must match the PC app exactly. The expected values come from `shared/contract/
 * portable-names.json`, which was generated by running the PC app's own functions, and which the PC
 * app's test suite also checks. Unit tests run with the module directory as the working directory.
 */
class FileNamesTest {
    private val fixture = JSONObject(File("../../shared/contract/portable-names.json").readText())

    @Test
    fun `names every segment exactly as the PC app does`() {
        val cases = fixture.getJSONArray("safeSegment")
        assertTrue("fixture should not be empty", cases.length() > 10)
        for (i in 0 until cases.length()) {
            val c = cases.getJSONObject(i)
            val max = if (c.has("max")) c.getInt("max") else 80
            assertEquals("segment ${c.getString("input").take(30)}", c.getString("expected"), FileNames.safeSegment(c.getString("input"), max))
        }
    }

    @Test
    fun `files every item at the same drive path as the PC app does`() {
        val cases = fixture.getJSONArray("target")
        assertTrue(cases.length() >= 5)
        for (i in 0 until cases.length()) {
            val c = cases.getJSONObject(i)
            val artist = if (c.isNull("artist")) null else c.getString("artist")
            val got = FileNames.targetFor(c.getString("kind") == "audio", c.getString("path"), c.getString("title"), artist)
            assertEquals("target ${c.getString("title").take(30)}", c.getString("expected"), got)
        }
    }

    @Test
    fun `a leading dot is not an extension`() {
        assertEquals("", FileNames.extensionOf("/x/.hidden"))
        assertEquals(".opus", FileNames.extensionOf("C:\\m\\a.opus"))
    }
}

class PlaybackSpeedTest {
    @Test
    fun `steps one rung at a time and stops at the ends`() {
        assertEquals(1.25f, PlaybackSpeed.step(1f, 1))
        assertEquals(0.75f, PlaybackSpeed.step(1f, -1))
        assertEquals(2f, PlaybackSpeed.step(2f, 1))
        assertEquals(0.25f, PlaybackSpeed.step(0.25f, -1))
    }

    @Test
    fun `a rate between rungs moves to the nearest rung in the direction asked`() {
        assertEquals(1.25f, PlaybackSpeed.step(1.1f, 1))
        assertEquals(1f, PlaybackSpeed.step(1.1f, -1))
    }

    @Test
    fun `junk becomes normal speed`() {
        assertEquals(1f, PlaybackSpeed.clamp(Float.NaN))
        assertEquals(1f, PlaybackSpeed.clamp(Float.POSITIVE_INFINITY))
        assertEquals(2f, PlaybackSpeed.clamp(16f))
        assertEquals(0.25f, PlaybackSpeed.clamp(-3f))
    }

    @Test
    fun `labels normal speed as Normal and the rest by multiplier`() {
        assertEquals("Normal", PlaybackSpeed.label(1f))
        assertEquals("1.5×", PlaybackSpeed.label(1.5f))
        assertEquals("2×", PlaybackSpeed.label(2f))
        assertEquals("0.25×", PlaybackSpeed.label(0.25f))
    }
}

class StreamPickerTest {
    private fun audio(kbps: Int, format: AudioFormat = AudioFormat.M4A, url: String = "u$kbps$format") = AudioOption(url, format, kbps, "x")
    private fun video(h: Int, codec: VideoCodec = VideoCodec.H264, fps: Int = 30, hasAudio: Boolean = false, url: String = "v$h$codec$fps") =
        VideoOption(url, h * 16 / 9, h, fps, codec, hasAudio, "mp4")

    @Test
    fun `picks the highest bitrate audio`() {
        assertEquals(256, StreamPicker.bestAudio(listOf(audio(128), audio(256), audio(160)))?.bitrateKbps)
    }

    @Test
    fun `prefers opus over aac at the same bitrate`() {
        val pick = StreamPicker.bestAudio(listOf(audio(128, AudioFormat.M4A), audio(128, AudioFormat.OPUS)))
        assertEquals(AudioFormat.OPUS, pick?.format)
    }

    @Test
    fun `ignores streams with no url and handles an empty list`() {
        assertNull(StreamPicker.bestAudio(emptyList()))
        assertNull(StreamPicker.bestAudio(listOf(audio(256, url = ""))))
    }

    @Test
    fun `never exceeds the height asked for`() {
        val pick = StreamPicker.bestVideo(listOf(video(2160), video(1080), video(720)), maxHeight = 1080)
        assertEquals(1080, pick?.height)
    }

    @Test
    fun `prefers h264 over vp9 at the same height because every tv decodes it`() {
        val pick = StreamPicker.bestVideo(listOf(video(1080, VideoCodec.VP9), video(1080, VideoCodec.H264)), 1080)
        assertEquals(VideoCodec.H264, pick?.codec)
    }

    @Test
    fun `leaves av1 out unless nothing else exists`() {
        assertEquals(720, StreamPicker.bestVideo(listOf(video(1080, VideoCodec.AV1), video(720)), 1080)?.height)
        assertEquals(VideoCodec.AV1, StreamPicker.bestVideo(listOf(video(1080, VideoCodec.AV1)), 1080)?.codec)
    }

    @Test
    fun `can insist on a video only stream when sound comes separately`() {
        val pick = StreamPicker.bestVideo(listOf(video(1080, hasAudio = true), video(720, hasAudio = false)), 1080, needsAudioStream = true)
        assertEquals(720, pick?.height)
    }

    @Test
    fun `prefers the higher frame rate at the same height and codec`() {
        assertEquals(60, StreamPicker.bestVideo(listOf(video(1080, fps = 30), video(1080, fps = 60)), 1080)?.fps)
    }

    @Test
    fun `gives nothing when no stream fits`() {
        assertNull(StreamPicker.bestVideo(listOf(video(2160)), 720))
    }

    @Test
    fun `lists one quality label per resolution tallest first`() {
        val labels = StreamPicker.qualityLabels(listOf(video(720), video(1080, fps = 60), video(1080), video(720, VideoCodec.VP9), video(360)))
        assertEquals(listOf("1080p60", "1080p", "720p", "360p"), labels)
    }
}

class ByteRangesTest {
    @Test
    fun `walks a file in chunks and ends exactly at the last byte`() {
        val total = 10L
        var have = 0L
        val seen = mutableListOf<ByteRanges.Range>()
        while (true) {
            val r = ByteRanges.next(have, total, chunk = 4) ?: break
            seen += r
            have = r.endInclusive + 1
        }
        assertEquals(listOf("bytes=0-3", "bytes=4-7", "bytes=8-9"), seen.map { it.header })
        assertEquals(total, seen.sumOf { it.length })
    }

    @Test
    fun `a complete or unrangeable file has no next range`() {
        assertNull(ByteRanges.next(10, 10))
        assertNull(ByteRanges.next(0, 0))
        assertNull(ByteRanges.next(0, -1))
        assertNull(ByteRanges.next(-5, 10))
    }

    @Test
    fun `resumes from a partial file and restarts one that is longer than the whole`() {
        assertEquals(0L, ByteRanges.resumeFrom(0, 100))
        assertEquals(40L, ByteRanges.resumeFrom(40, 100))
        assertEquals(0L, ByteRanges.resumeFrom(500, 100))
        assertEquals(500L, ByteRanges.resumeFrom(500, -1))
    }

    @Test
    fun `the first range of a fresh download starts at zero`() {
        assertNotNull(ByteRanges.next(0, 100))
        assertEquals(0L, ByteRanges.next(0, 100)?.start)
    }
}

class ArtworkUrlTest {
    @Test
    fun `asks YouTube Music for a bigger picture by changing the size in the url`() {
        assertEquals(
            "https://lh3.googleusercontent.com/AbC123=w800-h800-l90-rj",
            ArtworkUrl.large("https://lh3.googleusercontent.com/AbC123=w226-h226-l90-rj"),
        )
        assertEquals("https://yt3.ggpht.com/x=w1200-h1200", ArtworkUrl.large("https://yt3.ggpht.com/x=w60-h60", 1200))
    }

    @Test
    fun `leaves other hosts and unsized urls untouched`() {
        val ytimg = "https://i.ytimg.com/vi/abc/hqdefault.jpg"
        assertEquals(ytimg, ArtworkUrl.large(ytimg))
        val noSize = "https://lh3.googleusercontent.com/AbC123"
        assertEquals(noSize, ArtworkUrl.large(noSize))
    }

    @Test
    fun `passes null and blank through`() {
        assertNull(ArtworkUrl.large(null))
        assertEquals("", ArtworkUrl.large(""))
    }

    @Test
    fun `does not treat a lookalike host as resizable`() {
        val fake = "https://evil-googleusercontent.com.example.org/x=w10-h10"
        assertEquals(fake, ArtworkUrl.large(fake))
    }
}

class PlaylistLogicTest {
    private val id = "PLrAXtmErZgOeiKm4sgNOknGvNjby9efdf"

    @Test
    fun `finds the id in every kind of link people paste`() {
        assertEquals(PlaylistLogic.Parsed.Ok(id), PlaylistLogic.parse("https://www.youtube.com/playlist?list=$id"))
        assertEquals(PlaylistLogic.Parsed.Ok(id), PlaylistLogic.parse("https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=$id&index=3"))
        assertEquals(PlaylistLogic.Parsed.Ok(id), PlaylistLogic.parse("https://music.youtube.com/playlist?list=$id&si=abc"))
        assertEquals(PlaylistLogic.Parsed.Ok(id), PlaylistLogic.parse("  $id  "))
        assertEquals(PlaylistLogic.Parsed.Ok("LL"), PlaylistLogic.parse("https://www.youtube.com/playlist?list=LL"))
    }

    @Test
    fun `refuses a mix because it has nothing stable to sync`() {
        assertEquals(PlaylistLogic.Parsed.Mix, PlaylistLogic.parse("https://www.youtube.com/watch?v=abc&list=RDdQw4w9WgXcQ"))
    }

    @Test
    fun `rejects text that is not a playlist`() {
        assertEquals(PlaylistLogic.Parsed.Invalid, PlaylistLogic.parse(""))
        assertEquals(PlaylistLogic.Parsed.Invalid, PlaylistLogic.parse("hello world"))
        assertEquals(PlaylistLogic.Parsed.Invalid, PlaylistLogic.parse("https://www.youtube.com/watch?v=dQw4w9WgXcQ"))
        assertEquals(PlaylistLogic.Parsed.Invalid, PlaylistLogic.parse("PL12"))
    }

    @Test
    fun `new ids keep playlist order, appear once, and skip what is known`() {
        assertEquals(listOf("c", "d"), PlaylistLogic.newIds(listOf("a", "b", "c", "b", "d", "c"), setOf("a", "b")))
        assertEquals(emptyList<String>(), PlaylistLogic.newIds(listOf("a", "a"), setOf("a")))
        assertEquals(listOf("x"), PlaylistLogic.newIds(listOf("", "x", " "), emptySet()).filter { it.isNotBlank() })
    }

    @Test
    fun `is due when never synced, when the interval passed, or when the clock went backwards`() {
        val hour = 3_600_000L
        assertTrue(PlaylistLogic.isDue(0, 1_000_000, hour))
        assertTrue(!PlaylistLogic.isDue(1_000_000, 1_000_000 + hour - 1, hour))
        assertTrue(PlaylistLogic.isDue(1_000_000, 1_000_000 + hour, hour))
        assertTrue(PlaylistLogic.isDue(5_000_000, 1_000_000, hour))
    }

    @Test
    fun `estimates audio size from length and describes how long ago`() {
        assertEquals(16_000L * 60, PlaylistLogic.estimateAudioBytes(60))
        assertEquals(0L, PlaylistLogic.estimateAudioBytes(-5))
        assertEquals("never", PlaylistLogic.describeAge(0, 5000))
        assertEquals("just now", PlaylistLogic.describeAge(1000, 30_000))
        assertEquals("12 min ago", PlaylistLogic.describeAge(0 + 1, 12 * 60_000L + 1))
        assertEquals("3 h ago", PlaylistLogic.describeAge(1, 3 * 3_600_000L + 1))
        assertEquals("1 day ago", PlaylistLogic.describeAge(1, 86_400_000L + 1))
        assertEquals("2 days ago", PlaylistLogic.describeAge(1, 2 * 86_400_000L + 1))
    }
}

class FormsTest {
    @Test
    fun `reads a form body`() {
        val f = Forms.parse("link=https%3A%2F%2Fyoutu.be%2Fabc%3Flist%3DPLx&name=Road+trip&empty=")
        assertEquals("https://youtu.be/abc?list=PLx", f["link"])
        assertEquals("Road trip", f["name"])
        assertEquals("", f["empty"])
    }

    @Test
    fun `drops a broken escape instead of throwing`() {
        val f = Forms.parse("good=1&bad=%zz&alsogood=2")
        assertEquals("1", f["good"])
        assertNull(f["bad"])
        assertEquals("2", f["alsogood"])
    }

    @Test
    fun `is bounded in count and field size`() {
        val many = (1..100).joinToString("&") { "k$it=v" }
        assertEquals(32, Forms.parse(many).size)
        assertNull(Forms.parse("big=" + "x".repeat(5000))["big"])
    }

    @Test
    fun `compares secrets without early exit and escapes html`() {
        assertTrue(Forms.constantTimeEquals("4821", "4821"))
        assertTrue(!Forms.constantTimeEquals("4821", "4822"))
        assertTrue(!Forms.constantTimeEquals("4821", "48211"))
        assertTrue(!Forms.constantTimeEquals("", "x"))
        assertEquals("&lt;b&gt;&amp;&quot;&#39;", Forms.escapeHtml("<b>&\"'"))
    }
}

