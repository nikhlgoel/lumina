package com.lumina.tv.core

import com.lumina.tv.core.StreamPicker.AudioFormat
import com.lumina.tv.core.StreamPicker.AudioOption
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class SubtitlesAndAudioTracksTest {
    private fun sub(lang: String, label: String = lang, auto: Boolean = false, url: String = "u-$lang-$auto") =
        SubtitleOption(url, lang, label, "text/vtt", auto)

    @Test fun `preferred language first then English then the rest A to Z`() {
        val ordered = SubtitleRules.order(listOf(sub("fr", "French"), sub("en", "English"), sub("de", "German"), sub("hi", "Hindi")), preferredLanguage = "hi")
        // Hindi (chosen last time), English, then French before German.
        assertEquals(listOf("hi", "en", "fr", "de"), ordered.map { it.language })
    }

    @Test fun `written captions come before auto-generated ones of the same language`() {
        val ordered = SubtitleRules.order(listOf(sub("en", auto = true), sub("en", auto = false)), null)
        assertEquals(listOf(false, true), ordered.map { it.autoGenerated })
    }

    @Test fun `repeats of one language and kind are dropped`() {
        val ordered = SubtitleRules.order(listOf(sub("en", url = "a"), sub("en-US", url = "b")), null)
        assertEquals(1, ordered.size)
    }

    @Test fun `list is capped and blank urls are dropped`() {
        val many = (1..30).map { sub("l$it", "Lang%02d".format(it)) } + sub("zz", url = "")
        val ordered = SubtitleRules.order(many, null)
        assertEquals(SubtitleRules.MAX, ordered.size)
        assertTrue(ordered.none { it.url.isBlank() })
    }

    @Test fun `initial index finds the wanted language or turns captions off`() {
        val ordered = SubtitleRules.order(listOf(sub("en"), sub("fr")), null)
        assertEquals(1, SubtitleRules.initialIndex(ordered, "fr-CA"))
        assertEquals(-1, SubtitleRules.initialIndex(ordered, null))
        assertEquals(-1, SubtitleRules.initialIndex(ordered, "ja"))
    }

    @Test fun `labels mark auto-generated and survive a missing name`() {
        assertEquals("English", SubtitleRules.labelFor("English", "en", false))
        assertEquals("Hindi (auto-generated)", SubtitleRules.labelFor("Hindi", "hi", true))
        assertEquals("pt", SubtitleRules.labelFor("", "pt", false))
        assertEquals("Unknown", SubtitleRules.labelFor("", "", false))
    }

    private fun audio(id: String?, kbps: Int, label: String?, original: Boolean, format: AudioFormat = AudioFormat.M4A) =
        AudioOption("u-$id-$kbps-$format", format, kbps, "x", trackId = id, label = label, language = null, original = original)

    @Test fun `original language is the default even when a dub has a higher bitrate`() {
        val options = listOf(audio("en.4", 128, "English (original)", true), audio("hi.3", 256, "Hindi", false))
        val tracks = StreamPicker.audioTracks(options)
        assertEquals(listOf("English (original)", "Hindi"), tracks.map { it.label })
        assertEquals("en.4", StreamPicker.defaultAudioTrack(tracks)?.id)
        assertEquals(128, StreamPicker.bestAudio(options)?.bitrateKbps)
    }

    @Test fun `each track keeps its own best stream`() {
        val options = listOf(audio("en", 64, "English", true), audio("en", 128, "English", true), audio("fr", 48, "French", false))
        val tracks = StreamPicker.audioTracks(options)
        assertEquals(2, tracks.size)
        assertEquals(128, tracks.first { it.id == "en" }.best.bitrateKbps)
    }

    @Test fun `a video with one untagged track yields one entry`() {
        val tracks = StreamPicker.audioTracks(listOf(audio(null, 128, null, false), audio(null, 64, null, false)))
        assertEquals(1, tracks.size)
        assertNull(tracks[0].id)
        assertEquals("Audio", tracks[0].label)
    }

    @Test fun `no tracks gives no default`() {
        assertNull(StreamPicker.defaultAudioTrack(StreamPicker.audioTracks(emptyList())))
    }
}
