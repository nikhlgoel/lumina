export type Settings = z.infer<typeof settingsSchema>;
export type SettingsSection = keyof Omit<Settings, 'version'>;

/** Deep-partial patch accepted by settings:update. */
export type SettingsPatch = { [K in SettingsSection]?: Partial<Settings[K]> };

export const defaultSettings = (): Settings => settingsSchema.parse({});

export function mergeSettings(current: Settings, patch: SettingsPatch): Settings {
  const next: Record<string, unknown> = { ...current };
  for (const [key, values] of Object.entries(patch)) {
    if (!values || key === 'version') continue;
    next[key] = { ...(current as unknown as Record<string, object>)[key], ...values };
  }
  return settingsSchema.parse(next);
}

/** yt-dlp options that could run programs or change where Lumina reads config or writes files. */
const BLOCKED_ARGS = /^--?(exec|exec-before-download|batch-file|a|config-location|config-locations|plugin-dirs|load-info-json|output|o|paths|P|ffmpeg-location|downloader|external-downloader|downloader-args|external-downloader-args|print-to-file|update|update-to|U|cookies|cookies-from-browser)(=|$)/;

/** Split a user-typed argument string, respecting quotes. Blocked options return an error. */
export function parseExtraArgs(input: string): { args: string[]; error: string | null } {
  const args: string[] = [];
  for (const m of input.matchAll(/"([^"]*)"|'([^']*)'|(\S+)/g)) args.push(m[1] ?? m[2] ?? m[3] ?? '');
  const blocked = args.find((a) => BLOCKED_ARGS.test(a));
  return blocked
    ? { args: [], error: `“${blocked}” isn’t allowed here because it can run programs or change file locations.` }
    : { args, error: null };
}

/** Whether the speed limit applies at this moment (always, or only inside the scheduled window). */
export function speedLimitActive(s: Settings, now = new Date()): boolean {
  if (s.downloads.speedLimitKbps <= 0) return false;
  const sch = s.downloads.speedLimitSchedule;
  if (!sch.enabled) return true;
  const minutes = now.getHours() * 60 + now.getMinutes();
  const toMinutes = (t: string) => Number(t.slice(0, 2)) * 60 + Number(t.slice(3, 5));
  const from = toMinutes(sch.from);
  const to = toMinutes(sch.to);
  return from <= to ? minutes >= from && minutes < to : minutes >= from || minutes < to;
}
