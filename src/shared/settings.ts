const clampInt = (min: number, max: number, fallback: number) =>
  z.coerce.number().int().min(min).max(max).catch(fallback);
const clampNum = (min: number, max: number, fallback: number) =>
  z.coerce.number().min(min).max(max).catch(fallback);
const time = (fallback: string) => z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/).catch(fallback);
const hexColor = (fallback: string) => z.string().regex(/^#[0-9a-fA-F]{6}$/).catch(fallback);

/** An object whose every field has a fallback, so a missing or partial section parses to defaults. */
const section = <T extends z.ZodRawShape>(shape: T) =>
  z.object(shape).prefault({} as z.input<z.ZodObject<T>>);

